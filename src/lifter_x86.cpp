void Lifter::Impl::execX86(const Insn& in) {
    const ZydisDecodedInstruction& z = in.zi;
    auto dstReg = [&]() -> int {
        return in.ops[0].type == ZYDIS_OPERAND_TYPE_REGISTER ? regIndex(in.ops[0].reg.value) : -1;
    };
    switch (z.mnemonic) {
    case ZYDIS_MNEMONIC_NOP:
        if (info.dataKeys.count(in.addr)) {
            for (const DataLine& d : prog.dataLines)
                if (d.key == in.addr) addText("DATA" + d.text);
        }
        return;
    case ZYDIS_MNEMONIC_INT3:
    case ZYDIS_MNEMONIC_CLD:
    case ZYDIS_MNEMONIC_STD:
        return;
    case ZYDIS_MNEMONIC_MOV: {
        const auto& d = in.ops[0];
        const auto& s = in.ops[1];
        if (d.type == ZYDIS_OPERAND_TYPE_REGISTER && s.type == ZYDIS_OPERAND_TYPE_REGISTER && is16(d) && is16(s)) {
            int dr = regIndex(d.reg.value), sr = regIndex(s.reg.value);
            if (dr >= 0 && sr >= 0) st.r[dr] = st.r[sr];
            return;
        }
        if (d.type == ZYDIS_OPERAND_TYPE_MEMORY && s.type == ZYDIS_OPERAND_TYPE_REGISTER && is16(s)) {
            int sr = regIndex(s.reg.value);
            if (sr >= 0) {
                writeOperand(in, 0, nullptr, &st.r[sr]);
                return;
            }
        }
        if (d.type == ZYDIS_OPERAND_TYPE_REGISTER && s.type == ZYDIS_OPERAND_TYPE_MEMORY && is16(d) &&
            s.mem.base == ZYDIS_REGISTER_BP && s.mem.index == ZYDIS_REGISTER_NONE) {
            int off = s.mem.disp.has_displacement ? int(int16_t(s.mem.disp.value)) : 0;
            auto it = st.frame.find(off);
            if (it != st.frame.end()) {
                st.r[regIndex(d.reg.value)] = it->second;
                return;
            }
        }
        writeOperand(in, 0, operandValue(in, 1), nullptr);
        return;
    }
    case ZYDIS_MNEMONIC_XCHG: {
        int a = regIndex(in.ops[0].reg.value), b = regIndex(in.ops[1].reg.value);
        if (in.ops[0].type == ZYDIS_OPERAND_TYPE_REGISTER && in.ops[1].type == ZYDIS_OPERAND_TYPE_REGISTER && a >= 0 &&
            b >= 0) {
            std::swap(st.r[a], st.r[b]);
        } else {
            warn("xchg with memory");
        }
        return;
    }
    case ZYDIS_MNEMONIC_LEA: {
        int r = dstReg();
        const auto& m = in.ops[1].mem;
        int off = m.disp.has_displacement ? int(int16_t(m.disp.value)) : 0;
        if (m.base == ZYDIS_REGISTER_BP) {
            int k = paramIndexFor(proc, info, off);
            if (k >= 0) {
                auto e = std::make_shared<Expr>(*mkParam(k, Ty::Unknown));
                e->flags = 1; // address of an array descriptor parameter
                setReg(r, e);
            } else {
                setReg(r, mkUnknown("lea frame"));
            }
        } else if (m.base == ZYDIS_REGISTER_NONE) {
            setReg(r, mkInt(int16_t(off)));
        } else {
            setReg(r, simplifyInt(mkBinary(Op::Add, reg(regIndex(m.base)), mkInt(off), Ty::Int)));
        }
        return;
    }
    case ZYDIS_MNEMONIC_PUSH: {
        Val v;
        if (in.ops[0].type == ZYDIS_OPERAND_TYPE_REGISTER) {
            ZydisRegister r = in.ops[0].reg.value;
            if (r == ZYDIS_REGISTER_CS) v.e = mkRaw("cs");
            else if (r == ZYDIS_REGISTER_DS || r == ZYDIS_REGISTER_ES || r == ZYDIS_REGISTER_SS) v.e = mkRaw("seg");
            else if (regIndex(r) >= 0) v = st.r[regIndex(r)];
        } else {
            v.e = operandValue(in, 0);
        }
        st.stack.push_back(v);
        return;
    }
    case ZYDIS_MNEMONIC_POP: {
        Val v;
        if (st.stack.empty()) {
            // removes the return address of a GOSUB ("RETURN line")
            popRet = true;
            v.e = mkUnknown("ret addr");
        } else {
            v = st.stack.back();
            st.stack.pop_back();
        }
        if (in.ops[0].type == ZYDIS_OPERAND_TYPE_REGISTER && regIndex(in.ops[0].reg.value) >= 0)
            st.r[regIndex(in.ops[0].reg.value)] = v;
        return;
    }
    case ZYDIS_MNEMONIC_ADD:
    case ZYDIS_MNEMONIC_SUB:
    case ZYDIS_MNEMONIC_AND:
    case ZYDIS_MNEMONIC_OR:
    case ZYDIS_MNEMONIC_XOR: {
        Op op = z.mnemonic == ZYDIS_MNEMONIC_ADD ? Op::Add
              : z.mnemonic == ZYDIS_MNEMONIC_SUB ? Op::Sub
              : z.mnemonic == ZYDIS_MNEMONIC_AND ? Op::And
              : z.mnemonic == ZYDIS_MNEMONIC_OR  ? Op::Or
                                                 : Op::Xor;
        const auto& d = in.ops[0];
        const auto& s = in.ops[1];
        bool same = d.type == ZYDIS_OPERAND_TYPE_REGISTER && s.type == ZYDIS_OPERAND_TYPE_REGISTER &&
                    d.reg.value == s.reg.value;
        if (same && (op == Op::Xor || op == Op::Sub)) {
            if (d.reg.value == ZYDIS_REGISTER_AH) return; // xor ah,ah after IN
            writeOperand(in, 0, mkInt(0), nullptr);
            st.flags = Flags();
            return;
        }
        if (same && (op == Op::And || op == Op::Or)) {
            st.flags.kind = Flags::Test;
            st.flags.a = operandValue(in, 0);
            st.flags.b = nullptr;
            return;
        }
        if (d.type == ZYDIS_OPERAND_TYPE_REGISTER && !is16(d)) {
            writeOperand(in, 0, nullptr, nullptr);
            return;
        }
        // the compiler evaluates the right operand of commutative operators first
        bool commute = op != Op::Sub && d.type == ZYDIS_OPERAND_TYPE_REGISTER &&
                       (s.type == ZYDIS_OPERAND_TYPE_REGISTER ||
                        (s.type == ZYDIS_OPERAND_TYPE_MEMORY && s.mem.base == ZYDIS_REGISTER_NONE && s.mem.index == ZYDIS_REGISTER_NONE &&
                         isSimpleValue(operandValue(in, 0))));
        ExprPtr va = operandValue(in, 0), vb = operandValue(in, 1);
        if (commute && d.type == ZYDIS_OPERAND_TYPE_REGISTER && s.type == ZYDIS_OPERAND_TYPE_REGISTER) {
            // registers: the compiler evaluates the bigger operand first; keep that order
            commute = exprWeight(vb) >= exprWeight(va);
        }
        ExprPtr r = commute ? simplifyInt(mkBinary(op, vb, va, Ty::Int)) : simplifyInt(mkBinary(op, va, vb, Ty::Int));
        writeOperand(in, 0, r, nullptr);
        st.flags.kind = Flags::Test;
        st.flags.a = r;
        return;
    }
    case ZYDIS_MNEMONIC_INC:
    case ZYDIS_MNEMONIC_DEC: {
        ExprPtr r = simplifyInt(mkBinary(z.mnemonic == ZYDIS_MNEMONIC_INC ? Op::Add : Op::Sub, operandValue(in, 0),
                                         mkInt(1), Ty::Int));
        writeOperand(in, 0, r, nullptr);
        st.flags.kind = Flags::Test;
        st.flags.a = r;
        return;
    }
    case ZYDIS_MNEMONIC_NEG:
    case ZYDIS_MNEMONIC_NOT: {
        ExprPtr r = simplifyInt(mkUnary(z.mnemonic == ZYDIS_MNEMONIC_NEG ? Op::Neg : Op::Not, operandValue(in, 0), Ty::Int));
        writeOperand(in, 0, r, nullptr);
        st.flags.kind = Flags::Test;
        st.flags.a = r;
        return;
    }
    case ZYDIS_MNEMONIC_SHL: {
        int32_t n = 1;
        if (in.ops[1].type == ZYDIS_OPERAND_TYPE_IMMEDIATE) n = int32_t(in.ops[1].imm.value.u);
        else warn("shift by register");
        ExprPtr r = simplifyInt(mkBinary(Op::Mul, operandValue(in, 0), mkInt(1 << n), Ty::Int));
        writeOperand(in, 0, r, nullptr);
        st.flags.kind = Flags::Test;
        st.flags.a = r;
        return;
    }
    case ZYDIS_MNEMONIC_CMP:
        st.flags.kind = Flags::Cmp;
        // "CMP reg, x" is generated for "x REL value": the register holds the right operand
        // (a simple variable is used as the memory operand; an array element in memory is the right operand)
        st.flags.swapped = in.ops[0].type == ZYDIS_OPERAND_TYPE_REGISTER && in.ops[1].type == ZYDIS_OPERAND_TYPE_MEMORY &&
                           in.ops[1].mem.base == ZYDIS_REGISTER_NONE && in.ops[1].mem.index == ZYDIS_REGISTER_NONE &&
                           isSimpleValue(operandValue(in, 0));
        st.flags.a = operandValue(in, st.flags.swapped ? 1 : 0);
        st.flags.b = operandValue(in, st.flags.swapped ? 0 : 1);
        return;
    case ZYDIS_MNEMONIC_TEST:
        st.flags.kind = Flags::Test;
        st.flags.a = simplifyInt(mkBinary(Op::And, operandValue(in, 0), operandValue(in, 1), Ty::Int));
        return;
    case ZYDIS_MNEMONIC_CWD:
        setReg(DX, mkUnknown("cwd"));
        return;
    case ZYDIS_MNEMONIC_IMUL:
    case ZYDIS_MNEMONIC_MUL: {
        if (z.operand_count_visible == 1) {
            setReg(AX, simplifyInt(mkBinary(Op::Mul, operandValue(in, 0), reg(AX), Ty::Int)));
            setReg(DX, mkUnknown("imul high"));
        } else {
            ExprPtr a = operandValue(in, z.operand_count_visible == 3 ? 1 : 0);
            ExprPtr b = operandValue(in, z.operand_count_visible == 3 ? 2 : 1);
            writeOperand(in, 0, simplifyInt(mkBinary(Op::Mul, a, b, Ty::Int)), nullptr);
        }
        st.flags = Flags();
        return;
    }
    case ZYDIS_MNEMONIC_IDIV:
    case ZYDIS_MNEMONIC_DIV: {
        ExprPtr a = reg(AX), b = operandValue(in, 0);
        setReg(AX, simplifyInt(mkBinary(Op::IDiv, a, b, Ty::Int)));
        setReg(DX, simplifyInt(mkBinary(Op::Mod, a, b, Ty::Int)));
        st.flags = Flags();
        return;
    }
    case ZYDIS_MNEMONIC_IN:
        if (in.ops[0].reg.value == ZYDIS_REGISTER_AL || in.ops[0].reg.value == ZYDIS_REGISTER_AX) {
            ExprPtr port = in.ops[1].type == ZYDIS_OPERAND_TYPE_IMMEDIATE ? mkInt(int32_t(in.ops[1].imm.value.u)) : reg(DX);
            setReg(AX, mkFunc("INP", {port}, Ty::Int));
        }
        return;
    case ZYDIS_MNEMONIC_OUT: {
        ExprPtr port = in.ops[0].type == ZYDIS_OPERAND_TYPE_IMMEDIATE ? mkInt(int32_t(in.ops[0].imm.value.u)) : reg(DX);
        addText({P("OUT "), P(port, Ty::Int), P(", "), P(reg(AX), Ty::Int)});
        return;
    }
    case ZYDIS_MNEMONIC_CALL: {
        uint16_t t;
        if (in.branchTarget(t)) callNear(in, t);
        else if (z.opcode == 0x9A) callFar(in);
        else warn("indirect call");
        return;
    }
    case ZYDIS_MNEMONIC_JMP:
    case ZYDIS_MNEMONIC_RET:
    case ZYDIS_MNEMONIC_IRET:
        return;
    default:
        if (in.isJcc()) return;
        {
            char buf[128];
            std::snprintf(buf, sizeof buf, "unhandled instruction %s", program.dis().format(in).c_str());
            warn(buf);
        }
        // conservatively forget written registers
        for (int i = 0; i < z.operand_count; ++i)
            if (in.ops[i].type == ZYDIS_OPERAND_TYPE_REGISTER && (in.ops[i].actions & ZYDIS_OPERAND_ACTION_MASK_WRITE)) {
                int r = regIndex(in.ops[i].reg.value);
                if (r >= 0) setReg(r, mkUnknown("clobbered"));
            }
        return;
    }
}

void Lifter::Impl::execInsn(const LInsn& li) {
    if (li.idiom != IdiomKind::None) {
        execIdiom(li);
        return;
    }
    const Insn& in = *li.insn;
    if (in.isRt) execRt(in);
    else execX86(in);
}

void Lifter::Impl::execBlock(const Block& b) {
    block = &b;
    static std::vector<Stmt> scratch;
    scratch.clear();
    LiftedBlock& lb = results[procIndex][b.id];
    if (emit) {
        lb.stmts.clear();
        lb.reached = true;
        out = &lb.stmts;
    } else {
        out = &scratch;
    }
    pend = Pending();
    popRet = false;
    recentStores.clear();
    fnArgs.clear();
    fnResultOverride.clear();
    pendingFnResult = -1;
    int facWritesAtStart = facWrites;
    for (const LInsn& li : b.code) {
        curAddr = li.addr;
        execInsn(li);
    }
    // single line DEF FN: the value left in the FAC or AX is the result
    if (proc && proc->kind == ProcKind::DefFnSingle && b.term == TermKind::Ret) {
        FnInfo& fi = info.fns[proc->entry];
        if (facWrites != facWritesAtStart && st.fac.e) {
            fi.type = st.facTy;
            fi.body = st.fac.e;
        } else if (st.r[AX].e && st.r[AX].e->kind == EK::PtrTo) {
            fi.type = Ty::Str;
            fi.body = st.r[AX].e->args[0];
        } else {
            fi.type = Ty::Int;
            fi.body = st.r[AX].e;
        }
    }
    flushPendingStatements();
    if (pend.print) {
        warn("unterminated PRINT");
        printEnd();
    }
    if (pend.input) warn("unterminated INPUT");

    const LInsn& last = b.code.back();
    if (emit) {
        lb.cond = nullptr;
        if (b.term == TermKind::Cond && last.insn) lb.cond = condFromFlags(last.insn->zi.mnemonic);
        lb.returnWithTarget = b.term == TermKind::Jump && popRet;
    }
}

