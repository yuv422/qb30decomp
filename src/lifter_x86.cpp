ExprPtr Lifter::Impl::condFromFlags(ZydisMnemonic cc) {
    const Flags& f = st.flags;
    Op op;
    switch (cc) {
    case ZYDIS_MNEMONIC_JZ: op = Op::Eq; break;
    case ZYDIS_MNEMONIC_JNZ: op = Op::Ne; break;
    case ZYDIS_MNEMONIC_JL: case ZYDIS_MNEMONIC_JB: case ZYDIS_MNEMONIC_JS: op = Op::Lt; break;
    case ZYDIS_MNEMONIC_JLE: case ZYDIS_MNEMONIC_JBE: op = Op::Le; break;
    case ZYDIS_MNEMONIC_JNLE: case ZYDIS_MNEMONIC_JNBE: op = Op::Gt; break;
    case ZYDIS_MNEMONIC_JNL: case ZYDIS_MNEMONIC_JNB: case ZYDIS_MNEMONIC_JNS: op = Op::Ge; break;
    default:
        warn("unsupported condition");
        return mkUnknown("cc", Ty::Int);
    }
    switch (f.kind) {
    case Flags::Cmp:
    case Flags::RtCmp:
        return simplifyCond(mkBinary(f.kind == Flags::Cmp && f.swapped ? swapCompare(op) : op, f.a, f.b, Ty::Int));
    case Flags::Test: {
        auto e = std::make_shared<Expr>(*mkBinary(op, f.a, mkInt(0), Ty::Int));
        if (op == Op::Ne) e->flags = 2; // "and r,r / jnz": IF x THEN
        return simplifyCond(e);
    }
    default:
        warn("condition without compare");
        return mkUnknown("flags", Ty::Int);
    }
}

