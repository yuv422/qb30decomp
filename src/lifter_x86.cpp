void Lifter::Impl::callNear(const Insn& in, uint16_t target) {
    (void)in;
    flushPendingStatements();
    if (program.isFn(target)) {
        auto fit = info.fns.find(target);
        std::vector<ExprPtr> args;
        Ty t = Ty::Unknown;
        if (pass == 1) {
            info.fnCallStores[target].push_back(recentStores);
        }
        if (fit != info.fns.end()) {
            t = fit->second.type;
            for (uint16_t p : fit->second.params) {
                auto a = fnArgs.find(p);
                if (a != fnArgs.end() && !a->second.empty()) {
                    args.push_back(a->second.back());
                    a->second.pop_back();
                }
                else args.push_back(mkVar(p, Ty::Unknown));
            }
        }
        recentStores.clear();
        ExprPtr call = mkFnCall(target, args, t);
        // everything may have been clobbered by the function body
        for (int r = 0; r < NREG; ++r)
            if (r != BP && r != SP) setReg(r, mkUnknown("after FN"));
        // temp slots are numbered program wide, so they survive the call
        setFac(mkUnknown("after FN"), Ty::Unknown);
        const Proc* fp = program.procAt(target);
        bool multi = fp && fp->kind == ProcKind::DefFn;
        if (multi) {
            pendingFnResult = target;
            if (fit != info.fns.end() && fit->second.hasResultVar) fnResultOverride[fit->second.resultVar] = call;
        } else if (t == Ty::Sng || t == Ty::Dbl) {
            setFac(call, t);
        } else if (t == Ty::Str) {
            setReg(AX, mkPtrTo(call));
        } else if (t == Ty::Int) {
            setReg(AX, call);
        } else {
            // unknown in pass 1: offer the call everywhere it might be picked up
            setFac(call, Ty::Unknown);
            setReg(AX, call);
        }
        st.flags = Flags();
        return;
    }
    if (program.isSub(target)) {
        // QB environment programs call SUBs with PUSH CS / CALL
        char buf[32];
        std::snprintf(buf, sizeof buf, "sub%04X", target);
        callSub(target, buf, false);
        return;
    }
    Stmt s;
    s.kind = SK::Gosub;
    s.target = target;
    s.hasTarget = true;
    addStmt(s);
    recentStores.clear();
    State keep = st;
    st = unknownState();
    st.stack = keep.stack;
}

void Lifter::Impl::callFar(const Insn& in) {
    flushPendingStatements();
    uint16_t target;
    if (in.farCallTarget(target)) {
        char buf[32];
        std::snprintf(buf, sizeof buf, "sub%04X", target);
        callSub(target, buf, false);
    } else {
        callSub(0, program.externalName(in), true);
    }
}

void Lifter::Impl::callSub(uint16_t target, const std::string& name, bool external) {
    // remove the CS pushed by "PUSH CS / CALL near"
    if (!st.stack.empty() && st.stack.back().e && st.stack.back().e->kind == EK::Raw && st.stack.back().e->sval == "cs")
        st.stack.pop_back();
    int words = -1;
    const Proc* sp = external ? nullptr : program.procAt(target);
    if (sp && sp->retfBytes >= 0) words = sp->retfBytes / 2;
    if (words < 0 || words > int(st.stack.size())) words = int(st.stack.size());
    std::vector<ExprPtr> raw;
    for (int i = 0; i < words; ++i) {
        raw.push_back(st.stack.back().e);
        st.stack.pop_back();
    }
    // raw[0] is the last argument. Recognise array descriptors pushed on the stack.
    struct Arg { ExprPtr ptr; bool isArray = false; int dims = 0; int type = 0; };
    std::vector<Arg> args;
    for (size_t i = 0; i < raw.size();) {
        Arg a;
        a.ptr = raw[i];
        int32_t tw, addr;
        if (i + 1 < raw.size() && isIntLit(raw[i], &addr) && isIntLit(raw[i + 1], &tw) && (tw & 0x80) &&
            (tw & 0x7f) >= 1 && (tw & 0x7f) <= 4 && ((tw >> 8) & 0xff) >= 1 && ((tw >> 8) & 0xff) <= 8) {
            a.isArray = true;
            a.dims = (tw >> 8) & 0xff;
            a.type = tw & 0x7f;
            size_t n = size_t(4 + a.dims);
            i += std::min(n, raw.size() - i);
        } else {
            ++i;
        }
        args.push_back(a);
    }
    std::reverse(args.begin(), args.end());

    const SubInfo* si = nullptr;
    auto sit = info.subs.find(target);
    if (!external && sit != info.subs.end()) si = &sit->second;
    std::vector<ExprPtr> argExprs;
    SubInfo observed;
    for (size_t k = 0; k < args.size(); ++k) {
        const Arg& a = args[k];
        SubParam sp2;
        sp2.isArray = a.isArray;
        sp2.dims = a.dims;
        if (a.isArray) {
            static const Ty kTypes[] = {Ty::Unknown, Ty::Int, Ty::Sng, Ty::Dbl, Ty::Str};
            Ty t = kTypes[a.type];
            sp2.type = t;
            int32_t addr = 0;
            isIntLit(a.ptr, &addr);
            argExprs.push_back(mkRaw(std::string("@arrayarg"), t));
            // keep the array base so the emitter can name it
            auto e = std::make_shared<Expr>(*argExprs.back());
            e->addr = uint16_t(addr);
            e->ival = a.dims;
            argExprs.back() = e;
        } else {
            Ty t = Ty::Unknown;
            if (si && k < si->params.size()) t = si->params[k].type;
            ExprPtr v = deref(a.ptr, t);
            sp2.type = v->type;
            argExprs.push_back(v);
        }
        observed.params.push_back(sp2);
    }
    if (pass == 1 && !external) {
        SubInfo& s = info.subs[target];
        if (s.params.size() < observed.params.size()) s.params.resize(observed.params.size());
        for (size_t k = 0; k < observed.params.size(); ++k) {
            SubParam& d = s.params[k];
            const SubParam& o = observed.params[k];
            if (o.isArray) { d.isArray = true; d.dims = o.dims; if (o.type != Ty::Unknown) d.type = o.type; }
            else if (d.type == Ty::Unknown) d.type = o.type;
        }
        info.subCallArgs[target].push_back(argExprs);
    }

    std::vector<Part> parts{P("CALL " + name)};
    if (!argExprs.empty()) {
        parts.push_back(P("("));
        for (size_t k = 0; k < argExprs.size(); ++k) {
            if (k) parts.push_back(P(", "));
            parts.push_back(PK(argExprs[k]));
        }
        parts.push_back(P(")"));
    }
    addText(std::move(parts));
    State keep = st;
    st = unknownState();
    st.stack = keep.stack;
}

