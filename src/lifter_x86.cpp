ExprPtr Lifter::Impl::memLocation(const ZydisDecodedOperand& op, Ty t) {
    const auto& m = op.mem;
    int16_t disp = m.disp.has_displacement ? int16_t(m.disp.value) : 0;
    if (m.base == ZYDIS_REGISTER_NONE && m.index == ZYDIS_REGISTER_NONE) return locationValue(uint16_t(disp), t);
    int base = regIndex(m.base);
    if (m.index != ZYDIS_REGISTER_NONE) {
        // [bx+si+disp] forms are not generated by the compiler
        return mkUnknown("mem index", t);
    }
    if (base == BP) return mkUnknown("frame", t); // handled by callers
    ExprPtr r = reg(base);
    if (disp == 0) return deref(r, t);
    int32_t v;
    if (isIntLit(r, &v)) return locationValue(uint16_t(v + disp), t);
    return mkArrElem(uint16_t(disp), t, {r}, AF_ByteOffset);
}

// Index of the SUB parameter whose pointer lives at [bp+off].
static int paramIndexFor(const Proc* p, const GlobalInfo& info, int off) {
    if (!p || p->kind != ProcKind::Sub || off < 6 || p->retfBytes <= 0) return -1;
    auto it = info.subs.find(p->entry);
    // walk from the last parameter (at bp+6) upwards
    if (it != info.subs.end() && !it->second.params.empty()) {
        const auto& ps = it->second.params;
        int pos = 6;
        for (int k = int(ps.size()) - 1; k >= 0; --k) {
            int size = ps[k].isArray ? (4 + ps[k].dims) * 2 : 2;
            if (off >= pos && off < pos + size) return k;
            pos += size;
        }
        return -1;
    }
    int words = p->retfBytes / 2;
    int w = (off - 6) / 2;
    if (w >= words) return -1;
    return words - 1 - w;
}

ExprPtr Lifter::Impl::operandValue(const Insn& in, int i) {
    const ZydisDecodedOperand& op = in.ops[i];
    switch (op.type) {
    case ZYDIS_OPERAND_TYPE_REGISTER: {
        int r = regIndex(op.reg.value);
        if (r < 0) return mkUnknown("seg reg");
        if (op.reg.value == ZYDIS_REGISTER_AH || op.reg.value == ZYDIS_REGISTER_BH ||
            op.reg.value == ZYDIS_REGISTER_CH || op.reg.value == ZYDIS_REGISTER_DH)
            return mkUnknown("high byte");
        return reg(r);
    }
    case ZYDIS_OPERAND_TYPE_IMMEDIATE:
        if (op.size == 8 && !op.imm.is_signed) return mkInt(int32_t(op.imm.value.u & 0xff));
        return mkInt(int16_t(op.imm.value.s));
    case ZYDIS_OPERAND_TYPE_MEMORY: {
        if (op.mem.base == ZYDIS_REGISTER_BP && op.mem.index == ZYDIS_REGISTER_NONE) {
            int off = op.mem.disp.has_displacement ? int(int16_t(op.mem.disp.value)) : 0;
            auto it = st.frame.find(off);
            if (it != st.frame.end() && it->second.e) return it->second.e;
            int k = paramIndexFor(proc, info, off);
            if (k >= 0) return mkParam(k, Ty::Unknown);
            return mkUnknown("frame read");
        }
        return memLocation(op, Ty::Int);
    }
    default:
        return mkUnknown("operand");
    }
}

void Lifter::Impl::writeOperand(const Insn& in, int i, ExprPtr v, Val* src) {
    const ZydisDecodedOperand& op = in.ops[i];
    if (op.type == ZYDIS_OPERAND_TYPE_REGISTER) {
        int r = regIndex(op.reg.value);
        if (r < 0) return;
        if (!is16(op)) {
            // 8 bit writes: only "in al,dx" and friends are generated
            setReg(r, mkUnknown("8-bit"));
            return;
        }
        if (src) st.r[r] = *src;
        else setReg(r, std::move(v));
        return;
    }
    if (op.type == ZYDIS_OPERAND_TYPE_MEMORY) {
        if (op.mem.base == ZYDIS_REGISTER_BP && op.mem.index == ZYDIS_REGISTER_NONE) {
            int off = op.mem.disp.has_displacement ? int(int16_t(op.mem.disp.value)) : 0;
            Val nv;
            nv.e = src ? src->e : v;
            nv.fb = src ? src->fb : nullptr;
            st.frame[off] = nv;
            return;
        }
        lvalueMode = true;
        ExprPtr lhs = memLocation(op, Ty::Int);
        lvalueMode = false;
        if (lhs->kind != EK::Var && lhs->kind != EK::ArrElem && lhs->kind != EK::Param) {
            if (lhs->kind == EK::IntLit || lhs->kind == EK::SngLit) {
                warn("store to a literal");
            }
        }
        storeTo(lhs, src ? src->e : v, src);
    }
}

