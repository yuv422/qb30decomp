void Lifter::Impl::execIdiom(const LInsn& li) {
    int r = regIndex(li.reg);
    switch (li.idiom) {
    case IdiomKind::SetBool: {
        // reg was 0; it stays 0 when the jcc is taken, else becomes -1
        ExprPtr c = condFromFlags(li.cc);
        int32_t v;
        if (!isIntLit(reg(r), &v) || v != 0) warn("boolean idiom on non-zero register");
        setReg(r, simplifyCond(invertCond(c)));
        st.flags = Flags();
        break;
    }
    case IdiomKind::AbsInt:
        setReg(r, mkFunc("ABS", {reg(r)}, Ty::Int));
        st.flags = Flags();
        break;
    case IdiomKind::SgnInt:
        setReg(r, mkFunc("SGN", {reg(r)}, Ty::Int));
        st.flags = Flags();
        break;
    case IdiomKind::Wait: {
        std::vector<Part> parts{P("WAIT "), P(reg(DX), Ty::Int), P(", "), P(reg(CX), Ty::Int)};
        if (li.waitXor) {
            parts.push_back(P(", "));
            parts.push_back(P(reg(BX), Ty::Int));
        }
        addText(std::move(parts));
        setReg(AX, mkUnknown("wait"));
        break;
    }
    default:
        break;
    }
}

