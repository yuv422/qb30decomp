int regIndex(ZydisRegister r) {
    switch (r) {
    case ZYDIS_REGISTER_AX: case ZYDIS_REGISTER_AL: case ZYDIS_REGISTER_AH: return AX;
    case ZYDIS_REGISTER_CX: case ZYDIS_REGISTER_CL: case ZYDIS_REGISTER_CH: return CX;
    case ZYDIS_REGISTER_DX: case ZYDIS_REGISTER_DL: case ZYDIS_REGISTER_DH: return DX;
    case ZYDIS_REGISTER_BX: case ZYDIS_REGISTER_BL: case ZYDIS_REGISTER_BH: return BX;
    case ZYDIS_REGISTER_SP: return SP;
    case ZYDIS_REGISTER_BP: return BP;
    case ZYDIS_REGISTER_SI: return SI;
    case ZYDIS_REGISTER_DI: return DI;
    default: return -1;
    }
}

bool is16(const ZydisDecodedOperand& op) { return op.size == 16; }

// A value the compiler can use directly as an operand (variable or constant).
bool isSimpleValue(const ExprPtr& e) {
    return e && (e->kind == EK::Var || e->kind == EK::IntLit || e->kind == EK::Param);
}

